#!/usr/bin/env python3
"""Floor-1 monster avatars from the owner's 3D renders (owner 2026-11-18: 「怪物圖片要更新」).

The owner's local Claude rendered the monster models (textures and parts from the game resource pack
sao.zip; bone positions from the Exiled Order site's model data) and pushed them to inbox/ as
render_<NNN>_<model>.png, 1024x1024 transparent, face left 45°, camera pitch 14° (commit 771789f).
<NNN> is the in-game codex number. Only floor 1 has codex numbers on this site (data.js M[].num), so
only those renders are wired: matched by number, never by model file name or by looks.
Renders past the floor-1 codex (floor 2 / 3) are left out until a number -> codex name table exists.

  python3 -I tools/build_mobrenders.py <render dir> <repo> [<more numbers to skip, comma separated>]
  (render dir: e.g. `git archive 771789f inbox | tar -x -C <dir>`, then <dir>/inbox)

writes img/renders/<NNN>.png (cropped to the model, 128 px, 256 colours, like build_mobphotos.py)
and mobrenders.js: window.SAO_MOBRENDER = {src, by:{1:{<site monster name>: <path>}}}.
"""
import json, os, re, subprocess, sys
from PIL import Image

SRC_COMMIT = "771789f"
# checked by eye against the owner's codex screenshots (inbox/2026-11-04_codex_*, 2026-11-15_codex_*);
# these have no codex screenshot to check against, so they stay out until one exists
SKIP = {"037": "Smough, Fallen Devastator: no codex screenshot",
        "054": "Ika: the 2026-11-15 codex screenshot shows #054 still undiscovered"}


def png8(im):
    return im.convert("RGBA").quantize(256, method=Image.Quantize.FASTOCTREE)


def sq128(path):
    im = Image.open(path).convert("RGBA")
    bb = im.getchannel("A").getbbox()
    im = im.crop(bb)
    w, h = im.size
    s = max(w, h)
    sq = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    sq.paste(im, ((s - w) // 2, (s - h) // 2))
    return sq.resize((128, 128), Image.LANCZOS)


def site_f1(repo):
    js = ("global.window={};require(%s);"
          "console.log(JSON.stringify(window.SAO.M.filter(m=>m.num).map(m=>[m.num,m.name])))") % json.dumps(os.path.join(repo, "data.js"))
    return dict(json.loads(subprocess.check_output(["node", "-e", js], text=True)))


def main():
    rdir, repo = sys.argv[1], sys.argv[2]
    skip = set(SKIP) | set(x for x in (sys.argv[3] if len(sys.argv) > 3 else "").split(",") if x)
    nums = site_f1(repo)
    out = os.path.join(repo, "img", "renders")
    os.makedirs(out, exist_ok=True)
    by, left = {}, []
    for fn in sorted(os.listdir(rdir)):
        m = re.fullmatch(r"render_(\d{3})_(.+)\.png", fn)
        if not m:
            continue
        n = m.group(1)
        if n not in nums or n in skip:
            left.append(fn)
            continue
        p = "img/renders/%s.png" % n
        png8(sq128(os.path.join(rdir, fn))).save(os.path.join(repo, p), optimize=True)
        by[nums[n]] = p
    with open(os.path.join(repo, "mobrenders.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/build_mobrenders.py from the owner's renders (commit %s); do not edit by hand\n" % SRC_COMMIT)
        f.write("window.SAO_MOBRENDER=" + json.dumps({"src": SRC_COMMIT, "by": {"1": by}}, ensure_ascii=False) + ";\n")
    print("wired", len(by), "left out", len(left))
    for x in left:
        print("  left out:", x)


if __name__ == "__main__":
    main()
