#!/usr/bin/env python3
"""Monster avatars from the owner's in-game codex screenshots (owner 2026-11-18: 「怪物圖片使用截圖，渲染圖先保留」).

Input: the 128 px cut-outs made by tools/codex_thumbs.py (mob_<NNN>.png) from the codex screenshots in inbox/
(2026-11-04_codex_*, 2026-11-15_codex_*, picked frames of the owner's codex recordings).
Floor 1: <NNN> is the floor-1 codex number = data.js M[].num. Other floors number their codex from #001 again and the
site has no numbers there yet, so each one is listed in OTHER with the reason it is that monster.

  python3 -I tools/build_mobcodex.py <floor-1 thumbs dir> <repo> [<floor-3 thumbs dir>]

writes img/codex/f<floor>_<NNN>.png (256 colours) and mobcodex.js: window.SAO_MOBCODEX = {by:{<floor>:{<site name>: <path>}}}.
"""
import json, os, re, subprocess, sys
from PIL import Image

# floor -> {codex number: (site monster name, why)}
OTHER = {3: {"032": ("Juvenile Treant", "codex 2026-11-16: 幼年樹人 #032, region 蘭瓦烏拉沼澤, drops 75 / 35 / 10 % = the site's swamp Juvenile Treant (Dark Branch 75, Juvenile Bark 35, Juvenile Seed 10)")}}


def png8(im):
    return im.convert("RGBA").quantize(256, method=Image.Quantize.FASTOCTREE)


def site_f1(repo):
    js = ("global.window={};require(%s);"
          "console.log(JSON.stringify(window.SAO.M.filter(m=>m.num).map(m=>[m.num,m.name])))") % json.dumps(os.path.join(repo, "data.js"))
    return dict(json.loads(subprocess.check_output(["node", "-e", js], text=True)))


def main():
    d1, repo = sys.argv[1], sys.argv[2]
    d3 = sys.argv[3] if len(sys.argv) > 3 else None
    out = os.path.join(repo, "img", "codex")
    os.makedirs(out, exist_ok=True)
    by, left = {"1": {}}, []
    nums = site_f1(repo)
    for fn in sorted(os.listdir(d1)):
        m = re.fullmatch(r"mob_(\d{3})\.png", fn)
        if not m:
            continue
        n = m.group(1)
        if n not in nums:
            left.append("F1 #%s: no site monster with this codex number" % n)
            continue
        p = "img/codex/f1_%s.png" % n
        png8(Image.open(os.path.join(d1, fn))).save(os.path.join(repo, p), optimize=True)
        by["1"][nums[n]] = p
    if d3:
        by["3"] = {}
        for n, (name, _why) in OTHER[3].items():
            src = os.path.join(d3, "mob_%s.png" % n)
            p = "img/codex/f3_%s.png" % n
            png8(Image.open(src)).save(os.path.join(repo, p), optimize=True)
            by["3"][name] = p
    with open(os.path.join(repo, "mobcodex.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/build_mobcodex.py from the owner's codex screenshots (tools/codex_thumbs.py cut-outs); do not edit by hand\n")
        f.write("window.SAO_MOBCODEX=" + json.dumps({"by": by}, ensure_ascii=False) + ";\n")
    print("wired", sum(len(v) for v in by.values()))
    for x in left:
        print("  left out:", x)


if __name__ == "__main__":
    main()
